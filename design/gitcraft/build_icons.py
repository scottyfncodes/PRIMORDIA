"""Turn the VectorCraft icon exports (design/gitcraft/icons/icon-*.svg) into src/ui/icons.ts.
Strokes become currentColor so CSS colours each icon. Run: python3 design/gitcraft/build_icons.py"""
import glob, os, re
here = os.path.dirname(os.path.abspath(__file__))
out = {}
for f in sorted(glob.glob(os.path.join(here, 'icons', 'icon-*.svg'))):
    name = os.path.basename(f)[5:-4]
    svg = open(f).read()
    body = re.search(r'<g[^>]*>(.*)</g>', svg, re.S).group(1)
    body = re.sub(r'\s(id|data-name)="[^"]*"', '', body)
    body = body.replace('stroke="#e8fffa"', '').replace(' stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round"', '')
    body = re.sub(r'\s+', ' ', body).strip()
    out[name] = body
lines = ["// Generated by design/gitcraft/build_icons.py from the GITCRAFT VectorCraft icon set. Do not edit by hand.",
         "export const ICON_PATHS: Record<string, string> = {"]
lines += [f"  {k}: '{v}'," for k, v in out.items()]
lines += ["};", "",
          "/** Inline SVG for an icon; stroke follows the surrounding text colour. */",
          "export function icon(name: string, cls = 'ico'): string {",
          "  const p = ICON_PATHS[name];",
          "  return p ? `<svg class=\"${cls}\" viewBox=\"0 0 24 24\" fill=\"none\" stroke=\"currentColor\" stroke-width=\"1.7\" stroke-linecap=\"round\" stroke-linejoin=\"round\" aria-hidden=\"true\">${p}</svg>` : '';",
          "}", ""]
open(os.path.join(here, '..', '..', 'src', 'ui', 'icons.ts'), 'w').write('\n'.join(lines))
print(list(out))
